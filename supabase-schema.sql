create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at before update on public.tasks
for each row execute function public.set_updated_at();

drop trigger if exists projects_set_updated_at on public.projects;
create trigger projects_set_updated_at before update on public.projects
for each row execute function public.set_updated_at();

-- Keeps the denormalised text columns and the foreign keys agreeing with each
-- other, and stamps completed_at / created_by / updated_by. The app writes
-- names; the database resolves them to ids.
create or replace function public.tasks_sync_links()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  select id into new.project_id from public.projects where name = new.project;
  select id into new.assignee_id from public.profiles where display_name = new.assignee;

  if tg_op = 'INSERT' then
    new.created_by = coalesce(new.created_by, auth.uid());
    new.updated_by = coalesce(new.updated_by, auth.uid());
    if new.completed and new.completed_at is null then
      new.completed_at = now();
    end if;
  else
    new.updated_by = auth.uid();
    if new.completed and not old.completed then
      new.completed_at = now();
    elsif not new.completed and old.completed then
      new.completed_at = null;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_sync_links_trigger on public.tasks;
create trigger tasks_sync_links_trigger before insert or update on public.tasks
for each row execute function public.tasks_sync_links();

-- Renaming a project used to orphan every task pointing at the old name.
create or replace function public.projects_cascade_rename()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.name is distinct from old.name then
    -- Match on the old name as well: a task written before project_id existed,
    -- or one whose project was created after it, carries a null project_id and
    -- would otherwise keep pointing at a name nobody uses any more.
    update public.tasks
    set project = new.name
    where project_id = new.id or (project_id is null and project = old.name);
  end if;
  return new;
end;
$$;

drop trigger if exists projects_cascade_rename_trigger on public.projects;
create trigger projects_cascade_rename_trigger after update on public.projects
for each row execute function public.projects_cascade_rename();

-- notes.entity_id is polymorphic, so it cannot carry a foreign key. Clean up by
-- hand instead of leaving orphaned notes behind.
create or replace function public.notes_cleanup()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from public.notes
  where entity_type = tg_argv[0] and entity_id = old.id;
  return old;
end;
$$;

drop trigger if exists tasks_notes_cleanup on public.tasks;
create trigger tasks_notes_cleanup after delete on public.tasks
for each row execute function public.notes_cleanup('task');

drop trigger if exists projects_notes_cleanup on public.projects;
create trigger projects_notes_cleanup after delete on public.projects
for each row execute function public.notes_cleanup('project');

-- Activity log.
create or replace function public.tasks_log_activity()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  who text;
begin
  select display_name into who from public.profiles where id = auth.uid();
  who = coalesce(who, 'Someone');

  if tg_op = 'INSERT' then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'created', new.name);
    return new;
  end if;

  if new.deleted_at is not null and old.deleted_at is null then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'deleted', '');
  elsif new.deleted_at is null and old.deleted_at is not null then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'restored', '');
  end if;

  if new.completed is distinct from old.completed then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, case when new.completed then 'completed' else 'reopened' end, '');
  end if;

  if new.assignee is distinct from old.assignee then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'reassigned', old.assignee || ' to ' || new.assignee);
  end if;

  if new.due is distinct from old.due then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'due date',
            coalesce(old.due::text, 'none') || ' to ' || coalesce(new.due::text, 'none'));
  end if;

  if new.status is distinct from old.status then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'status', old.status || ' to ' || new.status);
  end if;

  if new.name is distinct from old.name then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'renamed', new.name);
  end if;

  if new.priority is distinct from old.priority then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'priority', old.priority || ' to ' || new.priority);
  end if;

  -- Keyed off project_id, not the text column, so renaming a project does not
  -- log a move on every task that belongs to it.
  if new.project_id is distinct from old.project_id then
    insert into public.task_activity (task_id, actor_id, actor_name, action, detail)
    values (new.id, auth.uid(), who, 'moved',
            coalesce(old.project, 'none') || ' to ' || coalesce(new.project, 'none'));
  end if;

  return new;
end;
$$;

drop trigger if exists tasks_log_activity_trigger on public.tasks;
create trigger tasks_log_activity_trigger after insert or update on public.tasks
for each row execute function public.tasks_log_activity();

-- ---------------------------------------------------------------------------
-- Account creation
--
-- Signing up is gated on an invitation. When an invited address creates an
-- account, its profile is written for it and the invitation is marked claimed.
-- An address with no invitation gets an auth user with no profile, which every
-- policy below refuses, and the app tells them to ask the administrator.
-- ---------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  invite public.invitations%rowtype;
begin
  select * into invite
  from public.invitations
  where email = lower(trim(new.email)) and claimed_at is null;

  if not found then
    return new;
  end if;

  insert into public.profiles (id, display_name, role, title, office, accent, sort_order)
  values (new.id, invite.display_name, invite.role, invite.title, invite.office, invite.accent, invite.sort_order)
  on conflict (id) do nothing;

  update public.invitations
  set claimed_at = now(), claimed_by = new.id
  where email = invite.email;

  return new;
exception when others then
  -- Never let a provisioning problem turn into "Database error saving new
  -- user". The account is created without a profile, which is a state the app
  -- already explains, and the administrator can repair it with one insert.
  raise warning 'handle_new_user failed for %: %', new.email, sqlerrm;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

/*
 * Lets the sign-up screen say "that address has not been invited" before it
 * creates anything. Returns a boolean and nothing else, so it cannot be used
 * to read the invitation list.
 */
create or replace function public.email_is_invited(check_email text)
returns boolean language sql security definer set search_path = public stable as $$
  select exists (
    select 1 from public.invitations
    where email = lower(trim(check_email)) and claimed_at is null
  );
$$;

revoke all on function public.email_is_invited(text) from public;
grant execute on function public.email_is_invited(text) to anon, authenticated;

/*
 * Membership is having a profile row, not merely holding a token. Every policy
 * below is written in terms of this, so an account that signed up without an
 * invitation can read nothing.
 */
create or replace function public.is_workspace_member()
returns boolean language sql security definer set search_path = public stable as $$
  select exists (select 1 from public.profiles where id = auth.uid());
$$;

create or replace function public.is_workspace_admin()
returns boolean language sql security definer set search_path = public stable as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and role = 'admin'
  );
$$;

