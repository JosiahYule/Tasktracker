-- Tasktracker schema.
--
-- This file is idempotent: run the whole thing in the Supabase SQL Editor on a
-- brand new project OR on an existing one. Re-running it upgrades an older
-- database in place without touching your data.
--
-- Order matters: profiles and projects are created before tasks, because tasks
-- carries foreign keys into both.

-- ---------------------------------------------------------------------------
-- profiles
-- ---------------------------------------------------------------------------

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'member' check (role in ('member', 'admin')),
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists title text not null default '';
alter table public.profiles add column if not exists office text not null default '';
alter table public.profiles add column if not exists accent text not null default 'lavender';
alter table public.profiles add column if not exists active boolean not null default true;
alter table public.profiles add column if not exists sort_order integer not null default 100;

alter table public.profiles drop constraint if exists profiles_accent_check;
alter table public.profiles add constraint profiles_accent_check
  check (accent in ('coral', 'teal', 'blue', 'lavender', 'amber', 'rose'));

alter table public.profiles enable row level security;

-- ---------------------------------------------------------------------------
-- invitations
--
-- Who is allowed to create an account, and what their profile should say when
-- they do. The administrator adds a row per teammate; that person then sets
-- their own password in the app. Nobody has to copy user UUIDs by hand, and an
-- email that is not listed here cannot join the workspace.
-- ---------------------------------------------------------------------------

create table if not exists public.invitations (
  email text primary key,
  display_name text not null,
  role text not null default 'member' check (role in ('member', 'admin')),
  title text not null default '',
  office text not null default '',
  accent text not null default 'lavender',
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  claimed_by uuid references auth.users(id) on delete set null
);

alter table public.invitations drop constraint if exists invitations_accent_check;
alter table public.invitations add constraint invitations_accent_check
  check (accent in ('coral', 'teal', 'blue', 'lavender', 'amber', 'rose'));

-- Addresses are compared case-insensitively, so store them one way.
create or replace function public.normalise_invitation_email()
returns trigger language plpgsql as $$
begin
  new.email = lower(trim(new.email));
  return new;
end;
$$;

drop trigger if exists invitations_normalise_email on public.invitations;
create trigger invitations_normalise_email before insert or update on public.invitations
for each row execute function public.normalise_invitation_email();

update public.invitations set email = lower(trim(email)) where email <> lower(trim(email));

alter table public.invitations enable row level security;

-- ---------------------------------------------------------------------------
-- projects
-- ---------------------------------------------------------------------------

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 80),
  description text not null default '' check (char_length(description) <= 160),
  due date,
  color text not null default 'teal' check (color in ('coral', 'blue', 'teal', 'lavender')),
  created_at timestamptz not null default now()
);

alter table public.projects add column if not exists updated_at timestamptz not null default now();
alter table public.projects add column if not exists archived boolean not null default false;

alter table public.projects enable row level security;

-- ---------------------------------------------------------------------------
-- tasks
-- ---------------------------------------------------------------------------

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 200),
  assignee text not null,
  due date,
  project text not null default 'General',
  recurring boolean not null default false,
  frequency text not null default 'monthly' check (frequency in ('weekly', 'monthly', 'quarterly', 'yearly')),
  paused boolean not null default false,
  recurrence_generated boolean not null default false,
  status text not null default 'todo' check (status in ('todo', 'doing', 'waiting')),
  note text not null default '',
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.tasks add column if not exists priority text not null default 'normal';
alter table public.tasks add column if not exists completed_at timestamptz;
alter table public.tasks add column if not exists deleted_at timestamptz;
alter table public.tasks add column if not exists project_id bigint references public.projects(id) on delete set null;
alter table public.tasks add column if not exists assignee_id uuid references public.profiles(id) on delete set null;
alter table public.tasks add column if not exists created_by uuid references public.profiles(id) on delete set null;
alter table public.tasks add column if not exists updated_by uuid references public.profiles(id) on delete set null;

-- The original schema hardcoded two names into a check constraint, so hiring a
-- third person required a migration. Assignee is now validated by length only;
-- the app offers the choices from public.profiles.
alter table public.tasks drop constraint if exists tasks_assignee_check;
alter table public.tasks add constraint tasks_assignee_check
  check (char_length(assignee) between 1 and 80);

alter table public.tasks drop constraint if exists tasks_priority_check;
alter table public.tasks add constraint tasks_priority_check
  check (priority in ('low', 'normal', 'high'));

-- Handoff notes were capped at 180 characters, which truncated mid-sentence.
alter table public.tasks drop constraint if exists tasks_note_check;
alter table public.tasks add constraint tasks_note_check
  check (char_length(note) <= 400);

alter table public.tasks enable row level security;

-- ---------------------------------------------------------------------------
-- notes
-- ---------------------------------------------------------------------------

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('task', 'project')),
  entity_id bigint not null,
  body text not null check (char_length(body) between 1 and 1000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null,
  created_at timestamptz not null default now()
);

alter table public.notes enable row level security;

-- ---------------------------------------------------------------------------
-- task_activity
--
-- Who changed what, and when. An accounting team needs to be able to answer
-- that after the fact; before this table the only record of a reassignment or a
-- due-date change was the value itself.
-- ---------------------------------------------------------------------------

create table if not exists public.task_activity (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  actor_name text not null default '',
  action text not null,
  detail text not null default '',
  created_at timestamptz not null default now()
);

alter table public.task_activity enable row level security;

